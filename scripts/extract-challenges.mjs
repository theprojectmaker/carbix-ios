// Copies the web app's daily challenge pool into TypeScript so the two never drift.
import fs from 'node:fs';
const html = fs.readFileSync('../motordex/public/index.html', 'utf8');
const a = html.indexOf('const CH_POOL=[');
const b = html.indexOf('function dailyChallenges()');
let body = html.slice(a + 'const CH_POOL='.length, b).trim().replace(/;$/, '');
body = body.replace(/test:c=>/g, 'test:(c:any)=>');
const out = `/* GENERATED by scripts/extract-challenges.mjs from the web app. Do not edit by hand. */
export type Challenge = { id: string; label: string; n: number; xp: number; test: (c: any) => boolean };
export const CH_POOL: Challenge[] = ${body};
`;
fs.writeFileSync('src/engine/chPool.ts', out);
console.log('challenges', (body.match(/\{id:/g) || []).length);
