/**
 * Map pins as pixel art, one 14x19 mask per shape, drawn at render time in the catch's rarity colour.
 * '#' is the rarity colour; letters are fixed colours (stem, snow, leaf...). The renderer adds a one-pixel ink
 * outline, lights the upper-left edges and shades the lower-right, exactly like the PNGs the website serves, so the
 * Map, the Shop and the website show the same pin. Pure data and maths: no React here, Node can import it too.
 */
