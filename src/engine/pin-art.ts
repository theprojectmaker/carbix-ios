/** 'map-marker-<marker>' shop ids resolve to their shape; anything unknown gets no shape. */
export const shapeForPinId = (id: string): PinShape | null => PIN_SHAPES[id.replace(/^map-marker-/, '')] ?? null;

const hex = (h: string): [number, number, number] => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)) as [number, number, number];
const mix = (a: number[], b: number[], t: number) => a.map((v, i) => Math.round(v + (b[i] - v) * t));
const rgb = (c: number[]) => `rgb(${c[0]},${c[1]},${c[2]})`;
const lighter = (c: number[], t = 0.38) => mix(c, [255, 255, 255], t);
const darker = (c: number[], t = 0.3) => mix(c, [10, 14, 24], t);

/** The finished pin: every opaque pixel of the 16x21 grid, outline included. */
export function renderPin(shape: PinShape, rarityHex: string): Pixel[] {
  const { mask } = shape;
  const inM = (x: number, y: number) => y >= 0 && y < 19 && x >= 0 && x < 14 && mask[y][x] !== '.';
  const base = (ch: string) => hex(ch === '#' ? rarityHex : shape.fixed?.[ch] || FIXED[ch] || rarityHex);
  const out: Pixel[] = [];
  const ink = hex(INK);
  for (let y = -1; y <= 19; y++) {
    for (let x = -1; x <= 14; x++) {
      if (inM(x, y)) continue;
      let near = false;
      for (let dy = -1; dy <= 1 && !near; dy++) for (let dx = -1; dx <= 1; dx++) if ((dx || dy) && inM(x + dx, y + dy)) { near = true; break; }
      if (near) out.push({ x: x + 1, y: y + 1, c: rgb(ink) });
    }
  }
  const body = new Map<string, number[]>();
  for (let y = 0; y < 19; y++) {
    for (let x = 0; x < 14; x++) {
      const ch = mask[y][x];
      if (ch === '.') continue;
      const b = base(ch);
      const lit = !inM(x - 1, y) || !inM(x, y - 1);
      const shade = !inM(x + 1, y) || !inM(x, y + 1);
      body.set(`${x},${y}`, lit && !shade ? lighter(b) : shade && !lit ? darker(b) : b);
    }
  }
  for (const [x, y, kind] of shape.details || []) {
    const b = base(mask[y]?.[x] ?? '#');
    body.set(`${x},${y}`, kind === 'ink' ? ink : kind === 'white' ? [255, 255, 255] : kind === 'lighter' ? lighter(b, 0.55) : darker(b, 0.32));
  }
  for (const [k, c] of body) {
    const [x, y] = k.split(',').map(Number);
    out.push({ x: x + 1, y: y + 1, c: rgb(c) });
  }
  return out;
}
